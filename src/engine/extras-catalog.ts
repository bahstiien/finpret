/**
 * Bibliothèque des articles hors menu (§8.3) : ce qu'un foyer ajoute à sa liste en plus des ingrédients des repas
 * (yaourts, fruits, couches…), rangé dans les rayons de `seed/aisles.json`. `also` : autres façons de l'écrire,
 * pour la recherche. `top` : proposé d'emblée tant que le foyer n'a pas encore d'habitudes.
 * Aucune donnée nutritionnelle ni prix : seulement un nom et un rayon.
 */
export type Extra = { label: string; aisle: string; also?: string[]; top?: boolean };

const group = (aisle: string, items: (string | [string, string[]] | [string, string[], true])[]): Extra[] =>
  items.map((it) => {
    if (typeof it === "string") {
      const top = it.endsWith("*");
      const label = top ? it.slice(0, -1) : it;
      return top ? { label, aisle, top } : { label, aisle };
    }
    const [label, also, top] = it;
    return top ? { label, aisle, also, top } : { label, aisle, also };
  });

