export type IconName = keyof typeof GLYPHS;

export function Icon({
  name,
  className = "size-6",
  label,
}: {
  name: IconName;
  className?: string;
  label?: string;
}) {
  const Glyph = GLYPHS[name];
  return (
    <Glyph
      className={`shrink-0 ${className}`}
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
    />
  );
}
